#!/usr/bin/env bash
# Combine the C# source files emitted by Haxe into one C# compilation unit.
# C# requires using directives and assembly attributes to precede declarations,
# while Haxe emits one compilation unit per file.  This script hoists those
# declarations before concatenating the remaining generated source.
set -euo pipefail
IFS=$'\n\t'

if [[ $# -ne 3 ]]; then
  echo "Usage: $0 GENERATED_SRC_DIR OUTPUT_CS SOURCE_MAP_TXT" >&2
  exit 64
fi

generated_src_dir=$1
output_cs=$2
source_map=$3
notice_file="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)/THIRD-PARTY-NOTICES.txt"

if [[ ! -d "$generated_src_dir" ]]; then
  echo "Generated C# source directory does not exist: $generated_src_dir" >&2
  exit 1
fi

if [[ ! -f "$notice_file" ]]; then
  echo "Missing required license notice file: $notice_file" >&2
  exit 1
fi

mapfile -d '' cs_files < <(find "$generated_src_dir" -type f -name '*.cs' -print0 | LC_ALL=C sort -z)
if [[ ${#cs_files[@]} -eq 0 ]]; then
  echo "No generated C# files found in: $generated_src_dir" >&2
  exit 1
fi

output_dir=$(dirname "$output_cs")
map_dir=$(dirname "$source_map")
mkdir -p "$output_dir" "$map_dir"
output_tmp=$(mktemp "$output_dir/.Zsd.cs.XXXXXX")
map_tmp=$(mktemp "$map_dir/.Zsd.source-map.txt.XXXXXX")
declarations=$(mktemp)
body=$(mktemp)
trap 'rm -f "$output_tmp" "$map_tmp" "$declarations" "$body"' EXIT

: >"$declarations"
: >"$body"

awk -v declarations="$declarations" -v body="$body" -v generated_root="$generated_src_dir" '
    function append_declaration(text, key) {
      key = text
      gsub(/\n/, "\034", key)
      if (!(key in declarations_seen)) {
        declarations_seen[key] = 1
        print text >> declarations
      }
    }

    FNR == 1 {
      if (in_assembly_attribute) {
        print "Unterminated assembly attribute before " FILENAME > "/dev/stderr"
        exit 1
      }
      source_name = substr(FILENAME, length(generated_root) + 2)
      print "" >> body
      print "// ----- Haxe generated file: " source_name " -----" >> body
    }

    {
      line = $0

      if (in_assembly_attribute) {
        assembly_attribute = assembly_attribute "\n" line
        if (line ~ /\][[:space:]]*$/) {
          append_declaration(assembly_attribute)
          in_assembly_attribute = 0
          assembly_attribute = ""
        }
        next
      }

      # Hoist only complete root-level using/extern directives.  A statement
      # such as "using (...)" does not end in a semicolon and remains in body.
      if (line ~ /^[[:space:]]*using[[:space:]]+.*;[[:space:]]*$/ ||
          line ~ /^[[:space:]]*extern[[:space:]]+alias[[:space:]]+.*;[[:space:]]*$/) {
        append_declaration(line)
        next
      }

      if (line ~ /^[[:space:]]*\[assembly:/) {
        assembly_attribute = line
        if (line ~ /\][[:space:]]*$/) {
          append_declaration(assembly_attribute)
          assembly_attribute = ""
        } else {
          in_assembly_attribute = 1
        }
        next
      }

      print line >> body
    }

    END {
      if (in_assembly_attribute) {
        print "Unterminated assembly attribute in " source_name > "/dev/stderr"
        exit 1
      }
    }
  ' "${cs_files[@]}"

{
  cat <<'HEADER'
// <auto-generated />
// This file is generated by tools/zsd/build-zsd.sh using Haxe.
// It is a self-contained C# source compilation unit targeting .NET Framework 4.0.
// Haxe per-file using directives and assembly attributes are hoisted below.
// Haxe #line directives retained in this file map generated code to its Haxe sources.
// The distributable license notices are included below as comments.
// Zsd.source-map.txt beside this file inventories the retained Haxe source paths.

HEADER
  sed 's/^/\/\/ /' "$notice_file"
  printf '\n'
  cat "$declarations"
  cat "$body"
} >"$output_tmp"

{
  cat <<'HEADER'
# Zsd Haxe-to-C# source map manifest
#
# The authoritative source mapping is the #line directives retained in Zsd.cs.
# This manifest records the Haxe source paths referenced by those directives
# and the generated C# files that were combined, in deterministic order.

[generated-csharp-files]
HEADER
  for cs_file in "${cs_files[@]}"; do
    printf '%s\n' "${cs_file#"$generated_src_dir"/}"
  done
  cat <<'HEADER'

[haxe-source-paths]
HEADER
  { grep -hE '^[[:space:]]*#line [0-9]+ "' "${cs_files[@]}" || true; } |
    sed -E 's/^[[:space:]]*#line [0-9]+ "([^"]+)".*/\1/' |
    LC_ALL=C sort -u
} >"$map_tmp"

mv -f "$output_tmp" "$output_cs"
mv -f "$map_tmp" "$source_map"
